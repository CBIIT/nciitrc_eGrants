/* ── Badge pill with icon ── */
const colorMap: Record<string, string> = {
  blue: "bg-blue-50 text-blue-700 border-blue-200",
  amber: "bg-amber-50 text-amber-700 border-amber-200",
  rose: "bg-rose-50 text-rose-700 border-rose-200",
  emerald: "bg-emerald-50 text-emerald-700 border-emerald-200",
  purple: "bg-purple-50 text-purple-700 border-purple-200",
  slate: "bg-slate-50 text-slate-600 border-slate-200",
  cyan: "bg-cyan-50 text-cyan-700 border-cyan-200",
};

const activeColorMap: Record<string, string> = {
  blue: "bg-blue-600 text-white border-blue-700",
  amber: "bg-amber-600 text-white border-amber-700",
  rose: "bg-rose-600 text-white border-rose-700",
  emerald: "bg-emerald-600 text-white border-emerald-700",
  purple: "bg-purple-600 text-white border-purple-700",
  slate: "bg-slate-600 text-white border-slate-700",
  cyan: "bg-cyan-600 text-white border-cyan-700",
};

export function FlagBadge({ label, color, icon, title, small, onClick, active }: { label: string; color: string; icon: ReactNode; title?: string; small?: boolean; onClick?: () => void; active?: boolean }) {
  const sizeClass = small
    ? "px-1 py-0 rounded text-[8px]"
    : "px-1.5 py-0.5 rounded-full text-[10px]";
  const colors = active
    ? (activeColorMap[color] || activeColorMap.slate)
    : (colorMap[color] || colorMap.slate);
  const clickClass = onClick ? "cursor-pointer hover:opacity-80" : "cursor-default";
  const Tag = onClick ? "button" : "span";
  return (
    <Tag
      type={onClick ? "button" : undefined}
      onClick={onClick}
      className={`relative group inline-flex items-center gap-0.5 font-semibold border transition-all ${sizeClass} ${colors} ${clickClass}`}
    >
      {icon}
      {label}
      {title && (
        <span className="pointer-events-none absolute bottom-full left-1/2 -translate-x-1/2 mb-1.5 hidden group-hover:block whitespace-nowrap rounded bg-gray-800 px-2 py-1 text-[10px] font-normal text-white shadow-lg z-50">
          {title}
          <span className="absolute top-full left-1/2 -translate-x-1/2 border-4 border-transparent border-t-gray-800" />
        </span>
      )}
    </Tag>
  );
}
