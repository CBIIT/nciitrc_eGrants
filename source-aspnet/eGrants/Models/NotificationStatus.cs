namespace eGrants.Models
{
    /// <summary>
    /// The notification status model.
    /// </summary>
    public class NotificationStatus
    {
        /// <summary>
        /// Gets or sets the tag.
        /// </summary>
        public string? tag { get; set; }

        /// <summary>
        /// Gets or sets the full_grant_num.
        /// </summary>
        public string? full_grant_num { get; set; }

        /// <summary>
        /// Gets or sets the pa.
        /// </summary>
        public string? pa { get; set; }

        /// <summary>
        /// Gets or sets the id.
        /// </summary>
        public string? id { get; set; }

        /// <summary>
        /// Gets or sets the document_id.
        /// </summary>
        public string? document_id { get; set; }

        /// <summary>
        /// Gets or sets the document_date.
        /// </summary>
        public string? document_date { get; set; }

        /// <summary>
        /// Gets or sets the url.
        /// </summary>
        public string? url { get; set; }

        /// <summary>
        /// Gets or sets the category_name.
        /// </summary>
        public string? category_name { get; set; }
    }
}